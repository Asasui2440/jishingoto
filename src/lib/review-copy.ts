import type { Question } from "./content";

/** 振り返りは対象年齢に合わせ、正しい行動と必要な条件を短く示す。 */
export function reviewNotes(question: Question, audience: "child" | "adult" = "child"): string[] {
  const best = question.choices.reduce((a, b) => b.safety > a.safety ? b : a);
  const adult = audience === "adult";
  switch (best.id) {
    case "under-desk": return adult
      ? ["近くの丈夫な机の下に入り、頭を保護して脚をつかみます。", "ガラス製・不安定な机や離れた机には向かわず、その場で頭と首を守ってください。"]
      : ["すぐ近くの丈夫[じょうぶ]な机の下に入り、頭を守って脚[あし]を持とう。", "ガラス製[せい]や不安定な机、遠い机には向かわず、その場で頭と首を守ろう。"];
    case "cover": case "move-away": case "protect-head": case "curtain": return adult
      ? ["転倒・落下する物から距離を取り、低い姿勢で頭と首を守ります。", "すぐ近くに安全に入れる丈夫な机があれば下へ。揺れている中を走って探しに行かないでください。"]
      : ["倒[たお]れたり落ちたりする物から離[はな]れ、低い姿勢[しせい]で頭と首を守ろう。", "すぐ近くに丈夫[じょうぶ]な机があれば下へ。揺[ゆ]れている中を走って探[さが]しに行かないこと。"];
    case "shoes": case "clear-exit": return adult
      ? ["移動前に床の破片と通れる経路を確認し、安全に手が届く履物で足を保護します。", "靴を取りに破片の上を歩かないでください。移動が難しい場合は周囲に助けを求め、火や煙が迫る場合はその場に留まらず避難を優先します。"]
      : ["動く前に床[ゆか]の破片[はへん]と通れる道を確認[かくにん]しよう。靴[くつ]は安全に手が届[とど]く所にあれば履[は]こう。", "靴[くつ]を取るために破片[はへん]の上を歩かないこと。動けない時は周囲[しゅうい]に助けを求め、火や煙[けむり]が迫[せま]る時は避難[ひなん]を優先[ゆうせん]しよう。"];
    case "verify": return adult
      ? ["テレビ・ラジオの報道や、気象庁・自治体の公式情報を確認します。", "日時と対象地域を確認し、裏付けが取れないSNSの情報は拡散しないでください。"]
      : ["テレビ・ラジオや、気象庁[きしょうちょう]・自治体[じちたい]の公式情報[こうしきじょうほう]で確認[かくにん]しよう。", "気象庁[きしょうちょう]や自治体[じちたい]の発表と比[くら]べ、確[たし]かめられない情報[じょうほう]は広めないこと。"];
    case "kitchen-check": return adult
      ? ["揺れが収まったら足元と周囲を確認し、安全に近づける場合だけ火を消します。", "ガス臭があれば火や電気のスイッチを使わず離れてください。火や煙が広がっている場合は、消火より避難を優先します。"]
      : ["揺[ゆ]れが収[おさ]まってから、足元と周囲[しゅうい]を確認[かくにん]しよう。火の始末は家族に知らせ、安全を確[たし]かめてから。", "ガスのにおいがする時は、火や電気のスイッチを使わず離[はな]れよう。火や煙[けむり]が広がっている時は、近づかず避難[ひなん]を優先[ゆうせん]しよう。"];
    case "wait": return adult
      ? ["揺れている間はコンロへ向かわず、まず身を守ります。", "揺れが収まった後、安全に近づける場合だけ火を消します。ガス臭や火・煙がある場合は無理に近づかないでください。"]
      : ["揺[ゆ]れている間はコンロへ向かわず、まず身を守ろう。", "揺[ゆ]れが収[おさ]まってから家族に火の元を知らせよう。ガスのにおいや火・煙[けむり]がある場合は、無理に近づかないこと。"];
    default: return best.explanation;
  }
}
