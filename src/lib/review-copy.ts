import type { Question } from "./content";

/** 振り返りは対象年齢に合わせ、正しい行動と必要な条件を短く示す。 */
export function reviewNotes(question: Question, audience: "child" | "adult" = "child"): string[] {
  const best = question.choices.reduce((a, b) => b.safety > a.safety ? b : a);
  const adult = audience === "adult";
  switch (best.id) {
    case "under-desk": return adult
      ? ["近くの丈夫な机の下で膝をついて低い姿勢になり、両手で机の脚をつかみます。", "ガラス製・不安定な机や離れた机には向かわず、その場で頭と首を守ってください。"]
      : ["すぐ近くの丈夫[じょうぶ]な机の下で、ひざをついて低くなり、両手で机の脚[あし]を持とう。", "ガラス製[せい]や不安定な机、遠い机には向かわず、その場で頭と首を守ろう。"];
    case "cover": case "move-away": case "protect-head": case "curtain": return adult
      ? ["転倒・落下する物から距離を取り、低い姿勢で頭と首を守ります。", "すぐ近くに安全に入れる丈夫な机があれば下へ。揺れている中を走って探しに行かないでください。", "揺れている間に外へ飛び出すと、瓦・窓ガラス・看板などの落下物に当たるおそれがあります。"]
      : ["倒[たお]れたり落ちたりする物から離[はな]れ、低い姿勢[しせい]で頭と首を守ろう。", "すぐ近くに丈夫[じょうぶ]な机があれば下へ。揺[ゆ]れている中を走って探[さが]しに行かないようにしよう。", "揺れている間に外へ飛び出すと、瓦[かわら]・窓ガラス・看板[かんばん]などが落ちてくることがあるよ。"];
    case "shoes": case "clear-exit": return adult
      ? ["揺れが収まったら床と出口を確認し、破片を踏まずに通れる経路を探します。靴を取りに行くために、はだしでガラスの上を歩かないでください。", "足を守れる履物がなく安全に動けない、または閉じ込められた場合は助けを求めます。声が届かなければ電話・笛・物をたたく音で知らせ、救助が必要なら119へ。", "火や煙が迫るときは、その場にとどまらず、通れる別の経路での避難と救助要請を優先します。"]
      : ["揺れが収まったら、床と出口を見よう。ガラスの上をはだしで歩いて、靴を取りに行かないようにしよう。破片を踏まずに通れる道があるか確かめよう。", "安全に動けない時や閉じ込められた時は、助けを呼ぼう。声が届かなければ電話・笛[ふえ]・物をたたく音で知らせよう。救助が必要なら119へ。", "火や煙が近づいてきたら、その場にとどまらず、通れる別の道から逃げて助けを呼ぼう。"];
    case "verify": return adult
      ? ["テレビ・ラジオの報道や、気象庁・自治体の公式情報を確認します。", "日時と対象地域を確認し、裏付けが取れないSNSの情報は拡散しないでください。"]
      : ["テレビ・ラジオや、気象庁[きしょうちょう]・自治体[じちたい]の公式情報[こうしきじょうほう]で確認[かくにん]しよう。", "気象庁[きしょうちょう]や自治体[じちたい]の発表と比[くら]べ、確[たし]かめられない情報[じょうほう]は広めないようにしよう。"];
    case "kitchen-check": return adult
      ? ["揺れが収まったら足元と周囲を確認し、安全に近づける場合だけ火を消します。", "避難前は、可能な範囲でガス栓とメーターの元栓も閉めます。", "ガス臭があれば火や電気のスイッチを使わず離れてください。火や煙が広がっている場合は、消火より避難を優先します。"]
      : ["揺れが収まったら、足元を見て家族に火の元を知らせよう。安全に近づける時だけ火を消すよ。", "家を出る前は、安全に近づけるならガス栓[せん]や元栓[もとせん]も閉めるよう、家族と確認しよう。", "ガスのにおいがしたら、火や電気のスイッチを使わず離れよう。火や煙が広がっていたら、近づかず逃げよう。"];
    case "shelter-home-0": return adult ? best.explanation : ["家と周りの安全が確認でき、水・食べ物・トイレも使えるなら、家で過ごす方法もあるよ。", "後から火事や余震[よしん]で様子が変わることもあるから、家族と情報を確かめ続けよう。家で生活できなくなったら、避難先や支援[しえん]を相談しよう。"];
    case "shelter-damaged-0": return adult ? best.explanation : ["建物が傾[かたむ]くなど、倒れるおそれがある時は、避難所が開くのを待たずに離れよう。", "まず通れる道で安全な場所へ。その後で、家族や地域の案内を確かめて避難先を決めよう。"];
    case "open-exit": return adult ? ["揺れが収まったら足元と周囲を確認し、安全に近づける場合はドアを開けて出口を確保します。", "屋外でも落下物があるため、周囲を確認せず飛び出さないでください。"] : best.explanation;
    case "check-family": return adult ? ["自身の安全を確保したうえで、家族に声をかけて安否を確認します。", "救助が必要な場合は周囲に協力を求め、単独で重い家具を動かすなど無理な行動は避けてください。"] : best.explanation;
    case "wait": return adult
      ? ["揺れている間はコンロへ向かわず、まず身を守ります。", "揺れが収まった後、安全に近づける場合だけ火を消します。避難前は可能な範囲でガス栓・メーターの元栓も閉めます。", "ガス臭や火・煙がある場合は無理に近づかず、避難を優先してください。"]
      : ["揺[ゆ]れている間はコンロへ向かわず、まず身を守ろう。", "揺[ゆ]れが収[おさ]まってから家族に火の元を知らせよう。避難前は、無理なく近づける場合に元栓[もとせん]も閉めるよう伝えよう。", "ガスのにおいや火・煙[けむり]がある場合は、無理に近づかないようにしよう。"];
    default: return best.explanation;
  }
}
