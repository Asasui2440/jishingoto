export function findEvent(id: string) {
  return HAZARD_EVENTS.find((e) => e.id === id) ?? null;
}

export function findChoice(eventId: string, choiceId: string) {
  return findEvent(eventId)?.choices.find((c) => c.id === choiceId) ?? null;
}

