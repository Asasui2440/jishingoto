export type LatLng = { lat: number; lng: number };

/** 自治体オープンデータ由来の避難場所 */
export type Shelter = {
  id: string;
  name: string;
  /** 「指定緊急避難場所」「指定避難所」など、出典どおりの区分 */
  kind: string;
  address: string;
  position: LatLng;
  /** 出典。画面にそのまま出す */
  source: string;
  /** 対応している災害種別など、断定を避けた補足 */
  note?: string;
};

export type RouteKind = "short" | "safe";

export type RouteOption = {
  id: string;
  kind: RouteKind;
  label: string;
  /** 「距離が短い」「曲がる回数が少ない」など、説明できる事実だけを書く */
  notes: string[];
  distanceM: number;
  durationS: number;
  /** 経路の座標列（保存対象） */
  path: LatLng[];
  /** この経路で起こる判断イベントの数 */
  eventCount: number;
  /** デモ用に合成した経路か（実 API から取れなかったとき true） */
  demo?: boolean;
};

/** 判断イベントの種類 */
export type EventKind = "wall" | "fall" | "closed";

export type ChoiceId = "go" | "distance" | "detour";

export type EvacChoice = {
  id: ChoiceId;
  label: string;
  detail: string;
  /** 選択直後に短く出す文（詳しくは結果レポートへ） */
  feedback: string;
  /** 結果レポートで見せる、この選択の利点と注意点 */
  pros: string[];
  cons: string[];
  /**
   * 安全上の優先順位（ルールエンジン側の値）。
   * 3 が最も優先度が高い。◯✕ではなく「優先順位」なので、
   * 画面には点数として出さない。
   */
  priority: 1 | 2 | 3;
  /** この選択でかかる追加時間（秒）。迂回すると経路も切り替わる */
  extraSeconds: number;
  reroute: boolean;
};

export type HazardEvent = {
  id: string;
  kind: EventKind;
  /** 見出し。必ず「〜した想定」で書く */
  title: string;
  /** 状況説明 */
  situation: string;
  /** 判断の手がかり（公的資料にもとづく一般論） */
  hint: string;
  choices: EvacChoice[];
  /**
   * ストリートビューに重ねる想定範囲（％）。
   * 実在の建物の損壊を描き込まず、半透明の範囲と番号だけを重ねる。
   */
  zone: { x: number; y: number; w: number; h: number };
  /** 平常時に確認しておくとよいこと（結果レポートの最終アクション候補） */
  followUp: string;
  /** 根拠にした公的資料 */
  reference: { label: string; url: string };
};

