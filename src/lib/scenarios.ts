type Option = [label: string, reason: string];
function scenario(id: string, settings: RoomSetting[], topic: Scenario["topic"], phase: "during" | "after", situation: string, options: [Option, Option, Option], sources = settings.length === 1 && settings[0] === "classroom" ? [SCHOOL, TFD] : [TFD]): Scenario {
  const choices: Choice[] = options.map(([label, reason], index) => ({
    id: `${id}-${index}`, label, detail: "", safety: index === 0 ? 0.95 : 0.2,
    explanation: [reason],
  }));
  return { id, settings, topic, phase, axis: phase === "during" ? "initial" : topic === "shelter" ? "judgement" : "evacuation", category: topic === "shelter" ? "いつ・どこへ避難[ひなん]する？" : "別[べつ]の場面[ばめん]も練習[れんしゅう]", situation, adultSituation: situation.replace(/\[[^\]]*\]/g, ""), seconds: 0, choices, sources };
}

