export function pickScenario(setting: RoomSetting, topic: Scenario["topic"], phase: "during" | "after", random = Math.random): Question | undefined {
  const candidates = SCENARIOS.filter((q) => q.settings.includes(setting) && q.topic === topic && q.phase === phase);
  return candidates[Math.floor(random() * candidates.length)];
}

export function shuffleChoices(question: Question, random = Math.random): Question {
  const choices = [...question.choices];
  for (let i = choices.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [choices[i], choices[j]] = [choices[j], choices[i]];
  }
  return { ...question, choices };
}
