/** 小学生向けの原稿を変更せず、大人の出題時だけ問題・4択・振り返りを置き換える。 */
export function adultQuestion(question: Question): Question {
  const best = question.choices.reduce((a, b) => b.safety > a.safety ? b : a);
  const challenge = challengeFor(question, best.id);
  if (!challenge) return question;
  const choices: Choice[] = challenge.options.map(([label, detail, safety, reason], index) => ({
    id: index === 0 ? best.id : `${question.id}-adult-${index}`,
    label, detail, safety, explanation: [reason],
  }));
  return {
    ...question, category: challenge.title, situation: challenge.situation, adultSituation: challenge.situation,
    seconds: question.phase === "during" ? 20 : 25, choices,
    challenge: { takeaway: challenge.takeaway },
    sources: Array.from(new Map([TOKYO, ...(question.sources ?? [])].map(source => [source.url, source])).values()),
  };
}
